def _possessed(stem: str, tr_v: str, ipa_v: str, tr_c: str = "", ipa_c: str = "") -> dict:
    """The LEX entries of one word with every owner's suffix: بنتي, بنتك, بنتك#f ..."""
    out = {}
    for _, _, suffix, tag, tr, ends, vowel in OWNERS:
        tr_stem, ipa = (tr_v, ipa_v) if vowel else (tr_c or tr_v, ipa_c or ipa_v)
        out[stem + suffix + tag] = (tr_stem + tr, [f"{s} {e}" for s in ipa.split(" / ") for e in ends])
    return out


